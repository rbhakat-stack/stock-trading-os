    OPEN_RISK_DATA_INCOMPLETE = "OPEN_RISK_DATA_INCOMPLETE"
    MAX_POSITIONS_REACHED = "MAX_POSITIONS_REACHED"
    MAX_TRADES_REACHED = "MAX_TRADES_REACHED"
    DATA_QUALITY_FAILURE = "DATA_QUALITY_FAILURE"
    INSUFFICIENT_DATA = "INSUFFICIENT_DATA"
    INVALID_ACCOUNT_STATE = "INVALID_ACCOUNT_STATE"
    INVALID_RISK_POLICY = "INVALID_RISK_POLICY"
    INVALID_NUMERIC_INPUT = "INVALID_NUMERIC_INPUT"
