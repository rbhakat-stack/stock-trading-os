    UNCLEAR_STRUCTURE = "UNCLEAR_STRUCTURE"
    MIDDLE_OF_RANGE = "MIDDLE_OF_RANGE"
    POOR_LOCATION = "POOR_LOCATION"
    RR_BELOW_MINIMUM = "RR_BELOW_MINIMUM"
    NO_STRUCTURAL_STOP = "NO_STRUCTURAL_STOP"
    NO_VALID_TARGET = "NO_VALID_TARGET"
    VOLATILITY_TOO_LOW = "VOLATILITY_TOO_LOW"
    VOLATILITY_TOO_HIGH = "VOLATILITY_TOO_HIGH"
    VOLUME_TOO_LOW = "VOLUME_TOO_LOW"
    MULTITIMEFRAME_CONFLICT = "MULTITIMEFRAME_CONFLICT"
    EVENT_RISK = "EVENT_RISK"
    DAILY_LOSS_LIMIT_REACHED = "DAILY_LOSS_LIMIT_REACHED"
    WEEKLY_LOSS_LIMIT_REACHED = "WEEKLY_LOSS_LIMIT_REACHED"
    MAX_CONSECUTIVE_LOSSES_REACHED = "MAX_CONSECUTIVE_LOSSES_REACHED"
    PORTFOLIO_HEAT_EXCEEDED = "PORTFOLIO_HEAT_EXCEEDED"
